export const DEFAULT_SPINNER_CONFIG: SpinnerVerbsConfig = {
  enabled: true,
  selectedPacks: ['claude_default'],
  mode: 'append',
  customVerbs: [],
  intervalMs: 2600
};

const STORAGE_KEY = 'kraken_spinner_verbs_config';

export function getSpinnerVerbsConfig(): SpinnerVerbsConfig {
  if (typeof window === 'undefined') return DEFAULT_SPINNER_CONFIG;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_SPINNER_CONFIG;
    const parsed = JSON.parse(raw);
    return {
      enabled: parsed.enabled ?? true,
      selectedPacks: Array.isArray(parsed.selectedPacks) && parsed.selectedPacks.length > 0
        ? parsed.selectedPacks
        : ['claude_default'],
      mode: parsed.mode === 'replace' ? 'replace' : 'append',
      customVerbs: Array.isArray(parsed.customVerbs) ? parsed.customVerbs : [],
      intervalMs: typeof parsed.intervalMs === 'number' && parsed.intervalMs >= 1000 ? parsed.intervalMs : 2600
    };
  } catch {
    return DEFAULT_SPINNER_CONFIG;
  }
}

export function saveSpinnerVerbsConfig(config: SpinnerVerbsConfig): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
    window.dispatchEvent(new CustomEvent('kraken:spinner-verbs-updated', { detail: config }));
  } catch {}
}

export function getActiveVerbsList(config: SpinnerVerbsConfig = getSpinnerVerbsConfig()): string[] {
  let list: string[] = [];

  const packsMap = new Map(SPINNER_VERB_PACKS.map(p => [p.id, p.verbs]));

  if (config.mode === 'append') {
    list.push(...CLAUDE_DEFAULT_VERBS);
    for (const packId of config.selectedPacks) {
      if (packId !== 'claude_default') {
        const verbs = packsMap.get(packId);
        if (verbs) list.push(...verbs);
      } 
    }
  } else {
    for (const packId of config.selectedPacks) {
      const verbs = packsMap.get(packId);
      if (verbs) list.push(...verbs);
    }
  }

  if (Array.isArray(config.customVerbs) && config.customVerbs.length > 0) {
    list.push(...config.customVerbs.map(v => v.trim()).filter(Boolean));
  }

  if (list.length === 0) {
    return CLAUDE_DEFAULT_VERBS;
  }

  return Array.from(new Set(list));
}
